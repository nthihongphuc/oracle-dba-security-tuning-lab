-- ============================================================================
-- File:        01-security/02_safe_priv_mgmt_pkg.sql
-- Purpose:     SQL-Injection-Proof Dynamic Privilege Management Package
--              Uses DBMS_ASSERT identifier sanitization (SIMPLE_SQL_NAME,
--              QUALIFIED_SQL_NAME, SCHEMA_NAME, ENQUOTE_NAME), strict privilege
--              & object whitelists, Invoker's Rights (AUTHID CURRENT_USER),
--              safe SCHEMA.OBJECT splitting, and immutable autonomous audit log.
-- Execution:   Run in FREEPDB1 connected as SEC_ADMIN (or SYSDBA with
--              CURRENT_SCHEMA = SEC_ADMIN).
-- ============================================================================

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = sec_admin;

-- 1. Strict Object Whitelist Table (only pre-approved objects can be delegated)
CREATE TABLE sec_admin.sec_priv_object_whitelist (
  whitelist_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schema_name      VARCHAR2(128) NOT NULL,
  object_name      VARCHAR2(128) NOT NULL,
  allowed_privs    VARCHAR2(100) NOT NULL, -- CSV subset of: SELECT,INSERT,UPDATE,DELETE,EXECUTE
  is_active        CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  approved_by      VARCHAR2(128) DEFAULT USER NOT NULL,
  approved_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_sec_priv_whitelist UNIQUE (schema_name, object_name)
) TABLESPACE ts_sec_data;

-- 2. Immutable Audit Log for Every Dynamic Grant / Revoke Attempt
CREATE TABLE sec_admin.sec_priv_action_log (
  action_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_type      VARCHAR2(10)  NOT NULL CHECK (action_type IN ('GRANT', 'REVOKE')),
  privilege_name   VARCHAR2(30)  NOT NULL,
  schema_name      VARCHAR2(128) NOT NULL,
  object_name      VARCHAR2(128) NOT NULL,
  grantee_name     VARCHAR2(128) NOT NULL,
  outcome          VARCHAR2(20)  NOT NULL CHECK (outcome IN ('SUCCESS', 'REJECTED', 'FAILED')),
  detail_message   VARCHAR2(400),
  executed_by      VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  executed_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE ts_sec_data;

-- 3. Package Specification (Invoker's Rights prevents privilege escalation)
--    Note: In multi-user production deployments, attach a narrow CBAC role
--          (SELECT on sec_priv_object_whitelist + INSERT on sec_priv_action_log)
--          via GRANT <cbac_role> TO PACKAGE sec_admin.pkg_safe_priv_mgmt so
--          delegated callers never need direct DML grants on audit tables.
CREATE OR REPLACE PACKAGE sec_admin.pkg_safe_priv_mgmt
  AUTHID CURRENT_USER
AS
  -- Custom errors for security rejections
  e_invalid_privilege   EXCEPTION;
  e_object_not_allowed  EXCEPTION;
  e_invalid_identifier  EXCEPTION;

  PRAGMA EXCEPTION_INIT(e_invalid_privilege,  -20101);
  PRAGMA EXCEPTION_INIT(e_object_not_allowed, -20102);
  PRAGMA EXCEPTION_INIT(e_invalid_identifier, -20103);

  PROCEDURE register_whitelisted_object (
    p_schema_name   IN VARCHAR2,
    p_object_name   IN VARCHAR2,
    p_allowed_privs IN VARCHAR2
  );

  PROCEDURE grant_object_priv (
    p_privilege    IN VARCHAR2,
    p_schema_name  IN VARCHAR2,
    p_object_name  IN VARCHAR2,
    p_grantee      IN VARCHAR2
  );

  PROCEDURE revoke_object_priv (
    p_privilege    IN VARCHAR2,
    p_schema_name  IN VARCHAR2,
    p_object_name  IN VARCHAR2,
    p_grantee      IN VARCHAR2
  );

  -- Safe qualified "SCHEMA.OBJECT" entry points (blocks @dblink & multi-dot chains)
  PROCEDURE grant_qualified_object_priv (
    p_privilege        IN VARCHAR2,
    p_qualified_object IN VARCHAR2,
    p_grantee          IN VARCHAR2
  );

  PROCEDURE revoke_qualified_object_priv (
    p_privilege        IN VARCHAR2,
    p_qualified_object IN VARCHAR2,
    p_grantee          IN VARCHAR2
  );
END pkg_safe_priv_mgmt;
/
SHOW ERRORS PACKAGE sec_admin.pkg_safe_priv_mgmt

-- 4. Package Body
CREATE OR REPLACE PACKAGE BODY sec_admin.pkg_safe_priv_mgmt
AS
  -- Explicit mapping for ORA-44004 (DBMS_ASSERT.QUALIFIED_SQL_NAME failure)
  e_assert_invalid_qual_name EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_assert_invalid_qual_name, -44004);

  -- Autonomous logger ensures rejected SQL-injection probes are persisted even
  -- on caller rollback, with mandatory ROLLBACK handler to prevent ORA-06519.
  PROCEDURE log_action (
    p_action_type    IN VARCHAR2,
    p_privilege_name IN VARCHAR2,
    p_schema_name    IN VARCHAR2,
    p_object_name    IN VARCHAR2,
    p_grantee_name   IN VARCHAR2,
    p_outcome        IN VARCHAR2,
    p_detail_message IN VARCHAR2
  ) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT INTO sec_admin.sec_priv_action_log (
      action_type, privilege_name, schema_name, object_name,
      grantee_name, outcome, detail_message
    ) VALUES (
      p_action_type,
      SUBSTR(NVL(p_privilege_name, '<NULL>'), 1, 30),
      SUBSTR(NVL(p_schema_name,    '<NULL>'), 1, 128),
      SUBSTR(NVL(p_object_name,    '<NULL>'), 1, 128),
      SUBSTR(NVL(p_grantee_name,   '<NULL>'), 1, 128),
      p_outcome,
      SUBSTR(p_detail_message, 1, 400)
    );
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END log_action;

  -- Strict static privilege allow-list (blocks ALTER, DROP, INDEX, WITH GRANT OPTION,
  -- and guards against ORA-06502 buffer overflow on oversized injection payloads)
  FUNCTION normalize_and_validate_priv (
    p_privilege IN VARCHAR2
  ) RETURN VARCHAR2 IS
    v_trimmed VARCHAR2(4000);
  BEGIN
    IF p_privilege IS NULL THEN
      RAISE_APPLICATION_ERROR(-20101, 'Rejected NULL privilege.');
    END IF;

    v_trimmed := UPPER(TRIM(p_privilege));
    IF LENGTH(v_trimmed) <= 30
       AND v_trimmed IN ('SELECT', 'INSERT', 'UPDATE', 'DELETE', 'EXECUTE')
    THEN
      RETURN v_trimmed;
    END IF;

    RAISE_APPLICATION_ERROR(
      -20101,
      'Rejected privilege "' || SUBSTR(p_privilege, 1, 30) ||
      '". Only SELECT, INSERT, UPDATE, DELETE, and EXECUTE are permitted.'
    );
  END normalize_and_validate_priv;

  -- Validates and canonicalizes a CSV list of privileges before writing to whitelist
  FUNCTION normalize_priv_csv (
    p_allowed_privs IN VARCHAR2
  ) RETURN VARCHAR2 IS
    v_csv        VARCHAR2(4000) := TRIM(p_allowed_privs);
    v_count      PLS_INTEGER;
    v_token      VARCHAR2(4000);
    v_valid_priv VARCHAR2(30);
    v_result     VARCHAR2(100) := NULL;
  BEGIN
    IF v_csv IS NULL OR REGEXP_LIKE(REPLACE(v_csv, ' ', ''), '(^,|,,|,$)') THEN
      RAISE_APPLICATION_ERROR(-20101, 'p_allowed_privs must be a non-empty CSV of allowed privileges.');
    END IF;

    v_count := REGEXP_COUNT(v_csv, ',') + 1;
    FOR i IN 1 .. v_count LOOP
      v_token      := TRIM(REGEXP_SUBSTR(v_csv, '[^,]+', 1, i));
      v_valid_priv := normalize_and_validate_priv(v_token);
      IF v_result IS NULL THEN
        v_result := v_valid_priv;
      ELSIF INSTR(',' || v_result || ',', ',' || v_valid_priv || ',') = 0 THEN
        v_result := v_result || ',' || v_valid_priv;
      END IF;
    END LOOP;

    RETURN v_result;
  END normalize_priv_csv;

  -- Validates and safely quotes a simple unquoted Oracle identifier via DBMS_ASSERT.
  -- Explicitly traps ORA-44003 (SYS.DBMS_ASSERT.INVALID_SQL_NAME) and VALUE_ERROR.
  FUNCTION sanitize_identifier (
    p_raw_name IN VARCHAR2,
    p_label    IN VARCHAR2
  ) RETURN VARCHAR2 IS
    v_clean VARCHAR2(130);
  BEGIN
    IF p_raw_name IS NULL
       OR NOT REGEXP_LIKE(p_raw_name, '^[A-Za-z][A-Za-z0-9_$#]{0,127}$')
    THEN
      RAISE_APPLICATION_ERROR(
        -20103,
        'Rejected ' || p_label || ': must match ^[A-Za-z][A-Za-z0-9_$#]{0,127}$ (no quotes, spaces, or injection tokens).'
      );
    END IF;

    v_clean := SYS.DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_raw_name));
    RETURN SYS.DBMS_ASSERT.ENQUOTE_NAME(v_clean, capitalize => FALSE);
  EXCEPTION
    WHEN SYS.DBMS_ASSERT.INVALID_SQL_NAME OR VALUE_ERROR THEN
      RAISE_APPLICATION_ERROR(-20103, 'Rejected ' || p_label || ': failed DBMS_ASSERT.SIMPLE_SQL_NAME check.');
  END sanitize_identifier;

  -- Safely parses a qualified "SCHEMA.OBJECT" string while blocking @dblink and multi-dot abuse
  PROCEDURE split_qualified_object (
    p_qualified_object IN  VARCHAR2,
    o_schema_name      OUT VARCHAR2,
    o_object_name      OUT VARCHAR2
  ) IS
    v_qual    VARCHAR2(300);
    v_dot_pos PLS_INTEGER;
  BEGIN
    IF p_qualified_object IS NULL
       OR LENGTH(p_qualified_object) > 257
       OR REGEXP_LIKE(p_qualified_object, '[[:space:]@]')
    THEN
      RAISE_APPLICATION_ERROR(
        -20103,
        'Rejected qualified_object: NULL, whitespace, overlong, or DB-link (@) syntax is forbidden.'
      );
    END IF;

    BEGIN
      v_qual := SYS.DBMS_ASSERT.QUALIFIED_SQL_NAME(UPPER(p_qualified_object));
    EXCEPTION
      WHEN e_assert_invalid_qual_name OR SYS.DBMS_ASSERT.INVALID_SQL_NAME OR VALUE_ERROR THEN
        RAISE_APPLICATION_ERROR(
          -20103,
          'Rejected qualified_object: failed DBMS_ASSERT.QUALIFIED_SQL_NAME check.'
        );
    END;

    IF REGEXP_COUNT(v_qual, '\.') <> 1 THEN
      RAISE_APPLICATION_ERROR(
        -20103,
        'Rejected qualified_object: must specify exact two-part SCHEMA.OBJECT name.'
      );
    END IF;

    v_dot_pos     := INSTR(v_qual, '.');
    o_schema_name := SUBSTR(v_qual, 1, v_dot_pos - 1);
    o_object_name := SUBSTR(v_qual, v_dot_pos + 1);

    IF o_schema_name IS NULL OR o_object_name IS NULL THEN
      RAISE_APPLICATION_ERROR(-20103, 'Rejected qualified_object: empty schema or object segment.');
    END IF;
  END split_qualified_object;

  -- Verifies object + privilege pair is explicitly registered in the whitelist
  PROCEDURE assert_object_whitelisted (
    p_schema_upper IN VARCHAR2,
    p_object_upper IN VARCHAR2,
    p_priv_upper   IN VARCHAR2
  ) IS
    v_allowed_privs sec_admin.sec_priv_object_whitelist.allowed_privs%TYPE;
  BEGIN
    SELECT allowed_privs
      INTO v_allowed_privs
      FROM sec_admin.sec_priv_object_whitelist
     WHERE schema_name = p_schema_upper
       AND object_name = p_object_upper
       AND is_active   = 'Y';

    IF INSTR(',' || REPLACE(UPPER(v_allowed_privs), ' ', '') || ',', ',' || p_priv_upper || ',') = 0 THEN
      RAISE_APPLICATION_ERROR(
        -20102,
        'Privilege ' || p_priv_upper || ' is not whitelisted for ' || p_schema_upper || '.' || p_object_upper
      );
    END IF;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(
        -20102,
        'Target object ' || p_schema_upper || '.' || p_object_upper || ' is not in sec_priv_object_whitelist.'
      );
  END assert_object_whitelisted;

  PROCEDURE register_whitelisted_object (
    p_schema_name   IN VARCHAR2,
    p_object_name   IN VARCHAR2,
    p_allowed_privs IN VARCHAR2
  ) IS
    v_schema_q     VARCHAR2(130);
    v_object_q     VARCHAR2(130);
    v_schema       VARCHAR2(128);
    v_object       VARCHAR2(128);
    v_clean_privs  VARCHAR2(100);
  BEGIN
    v_schema_q    := sanitize_identifier(p_schema_name, 'schema_name');
    v_object_q    := sanitize_identifier(p_object_name, 'object_name');
    v_clean_privs := normalize_priv_csv(p_allowed_privs);

    BEGIN
      v_schema := SYS.DBMS_ASSERT.SCHEMA_NAME(UPPER(p_schema_name));
    EXCEPTION
      WHEN SYS.DBMS_ASSERT.INVALID_SCHEMA_NAME THEN
        RAISE_APPLICATION_ERROR(-20103, 'Rejected schema_name: schema does not exist in database.');
    END;
    v_object := UPPER(p_object_name);

    MERGE INTO sec_admin.sec_priv_object_whitelist tgt
    USING (SELECT v_schema AS schema_name, v_object AS object_name FROM dual) src
       ON (tgt.schema_name = src.schema_name AND tgt.object_name = src.object_name)
    WHEN MATCHED THEN
      UPDATE SET allowed_privs = v_clean_privs,
                 is_active     = 'Y',
                 approved_by   = USER,
                 approved_at   = SYSTIMESTAMP
    WHEN NOT MATCHED THEN
      INSERT (schema_name, object_name, allowed_privs, is_active)
      VALUES (v_schema, v_object, v_clean_privs, 'Y');
  END register_whitelisted_object;

  PROCEDURE execute_priv_ddl (
    p_action      IN VARCHAR2,
    p_privilege   IN VARCHAR2,
    p_schema_name IN VARCHAR2,
    p_object_name IN VARCHAR2,
    p_grantee     IN VARCHAR2
  ) IS
    v_priv         VARCHAR2(30);
    v_schema_q     VARCHAR2(130);
    v_object_q     VARCHAR2(130);
    v_grantee_q    VARCHAR2(130);
    v_schema_u     VARCHAR2(128);
    v_object_u     VARCHAR2(128);
    v_grantee_u    VARCHAR2(128);
    v_ddl          VARCHAR2(500);
    v_preposition  VARCHAR2(4) := CASE p_action WHEN 'GRANT' THEN 'TO' ELSE 'FROM' END;
  BEGIN
    v_priv      := normalize_and_validate_priv(p_privilege);
    v_schema_q  := sanitize_identifier(p_schema_name, 'schema_name');
    v_object_q  := sanitize_identifier(p_object_name, 'object_name');
    v_grantee_q := sanitize_identifier(p_grantee,     'grantee');

    v_schema_u  := UPPER(p_schema_name);
    v_object_u  := UPPER(p_object_name);
    v_grantee_u := UPPER(p_grantee);

    -- Prevent dangerous broad or system-account delegation
    IF v_grantee_u IN ('PUBLIC', 'SYS', 'SYSTEM') THEN
      RAISE_APPLICATION_ERROR(
        -20103,
        'Rejected grantee "' || v_grantee_u || '": dynamic delegation to PUBLIC, SYS, or SYSTEM is prohibited.'
      );
    END IF;

    -- Verify schema actually exists in the data dictionary
    BEGIN
      v_schema_u := SYS.DBMS_ASSERT.SCHEMA_NAME(v_schema_u);
    EXCEPTION
      WHEN SYS.DBMS_ASSERT.INVALID_SCHEMA_NAME THEN
        RAISE_APPLICATION_ERROR(
          -20103,
          'Rejected schema_name "' || v_schema_u || '": schema does not exist in database.'
        );
    END;

    -- Enforce object + privilege allow-list
    assert_object_whitelisted(v_schema_u, v_object_u, v_priv);

    -- Construct safe DDL strictly from whitelisted keywords + DBMS_ASSERT-quoted identifiers
    v_ddl := p_action || ' ' || v_priv || ' ON ' || v_schema_q || '.' || v_object_q ||
             ' ' || v_preposition || ' ' || v_grantee_q;

    EXECUTE IMMEDIATE v_ddl;

    log_action(p_action, v_priv, v_schema_u, v_object_u, v_grantee_u, 'SUCCESS', v_ddl);
  EXCEPTION
    WHEN e_invalid_privilege OR e_object_not_allowed OR e_invalid_identifier THEN
      log_action(p_action, p_privilege, p_schema_name, p_object_name, p_grantee, 'REJECTED', SQLERRM);
      RAISE;
    WHEN OTHERS THEN
      log_action(p_action, p_privilege, p_schema_name, p_object_name, p_grantee, 'FAILED', SQLERRM);
      RAISE;
  END execute_priv_ddl;

  PROCEDURE grant_object_priv (
    p_privilege    IN VARCHAR2,
    p_schema_name  IN VARCHAR2,
    p_object_name  IN VARCHAR2,
    p_grantee      IN VARCHAR2
  ) IS
  BEGIN
    execute_priv_ddl('GRANT', p_privilege, p_schema_name, p_object_name, p_grantee);
  END grant_object_priv;

  PROCEDURE revoke_object_priv (
    p_privilege    IN VARCHAR2,
    p_schema_name  IN VARCHAR2,
    p_object_name  IN VARCHAR2,
    p_grantee      IN VARCHAR2
  ) IS
  BEGIN
    execute_priv_ddl('REVOKE', p_privilege, p_schema_name, p_object_name, p_grantee);
  END revoke_object_priv;

  PROCEDURE grant_qualified_object_priv (
    p_privilege        IN VARCHAR2,
    p_qualified_object IN VARCHAR2,
    p_grantee          IN VARCHAR2
  ) IS
    v_schema VARCHAR2(128);
    v_object VARCHAR2(128);
  BEGIN
    BEGIN
      split_qualified_object(p_qualified_object, v_schema, v_object);
    EXCEPTION
      WHEN e_invalid_identifier THEN
        log_action('GRANT', p_privilege, '<QUALIFIED>', p_qualified_object, p_grantee, 'REJECTED', SQLERRM);
        RAISE;
    END;
    execute_priv_ddl('GRANT', p_privilege, v_schema, v_object, p_grantee);
  END grant_qualified_object_priv;

  PROCEDURE revoke_qualified_object_priv (
    p_privilege        IN VARCHAR2,
    p_qualified_object IN VARCHAR2,
    p_grantee          IN VARCHAR2
  ) IS
    v_schema VARCHAR2(128);
    v_object VARCHAR2(128);
  BEGIN
    BEGIN
      split_qualified_object(p_qualified_object, v_schema, v_object);
    EXCEPTION
      WHEN e_invalid_identifier THEN
        log_action('REVOKE', p_privilege, '<QUALIFIED>', p_qualified_object, p_grantee, 'REJECTED', SQLERRM);
        RAISE;
    END;
    execute_priv_ddl('REVOKE', p_privilege, v_schema, v_object, p_grantee);
  END revoke_qualified_object_priv;

END pkg_safe_priv_mgmt;
/
