-- 5. Negative Security Self-Test (Proves 7 SQL Injection & Escalation Vectors Are Blocked)
DECLARE
  v_blocked_count PLS_INTEGER := 0;
BEGIN
  -- Test A: SQL injection payload in grantee parameter
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'SELECT',
      p_schema_name => 'SEC_ADMIN',
      p_object_name => 'SEC_PRIV_ACTION_LOG',
      p_grantee     => 'CLERK_ALICE WITH GRANT OPTION'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_identifier THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 1/7] Blocked injection payload in grantee: ' || SQLERRM);
  END;

  -- Test B: Disallowed destructive privilege
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'ALTER',
      p_schema_name => 'SEC_ADMIN',
      p_object_name => 'SEC_PRIV_ACTION_LOG',
      p_grantee     => 'CLERK_ALICE'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_privilege THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 2/7] Blocked non-whitelisted privilege: ' || SQLERRM);
  END;

  -- Test C: Oversized privilege injection payload (must not raise ORA-06502)
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'SELECT ON DUAL TO ATTACKER; -- 12345678901234567890',
      p_schema_name => 'SEC_ADMIN',
      p_object_name => 'SEC_PRIV_ACTION_LOG',
      p_grantee     => 'CLERK_ALICE'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_privilege THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 3/7] Blocked oversized privilege payload cleanly: ' || SQLERRM);
  END;

  -- Test D: Invalid leading-digit identifier (verifies ORA-44003 / regex rejection)
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'SELECT',
      p_schema_name => 'SEC_ADMIN',
      p_object_name => '123_INVALID_OBJ',
      p_grantee     => 'CLERK_ALICE'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_identifier THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 4/7] Blocked invalid leading-digit object name: ' || SQLERRM);
  END;

  -- Test E: Broad privilege escalation to PUBLIC
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'SELECT',
      p_schema_name => 'SEC_ADMIN',
      p_object_name => 'SEC_PRIV_ACTION_LOG',
      p_grantee     => 'PUBLIC'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_identifier THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 5/7] Blocked PUBLIC grantee escalation: ' || SQLERRM);
  END;

  -- Test F: DB-link injection inside qualified SCHEMA.OBJECT@DBLINK
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_qualified_object_priv(
      p_privilege        => 'SELECT',
      p_qualified_object => 'SEC_ADMIN.SEC_PRIV_ACTION_LOG@EVIL_LINK',
      p_grantee          => 'CLERK_ALICE'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_invalid_identifier THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 6/7] Blocked DB-link injection in qualified object: ' || SQLERRM);
  END;

  -- Test G: Non-whitelisted object in valid schema
  BEGIN
    sec_admin.pkg_safe_priv_mgmt.grant_object_priv(
      p_privilege   => 'SELECT',
      p_schema_name => 'HOTEL_APP',
      p_object_name => 'INVOICES',
      p_grantee     => 'CLERK_ALICE'
    );
  EXCEPTION
    WHEN sec_admin.pkg_safe_priv_mgmt.e_object_not_allowed THEN
      v_blocked_count := v_blocked_count + 1;
      DBMS_OUTPUT.PUT_LINE('[PASS 7/7] Blocked non-whitelisted object access: ' || SQLERRM);
  END;

  IF v_blocked_count <> 7 THEN
    RAISE_APPLICATION_ERROR(-20999, 'Security self-test failed: expected 7 rejections, got ' || v_blocked_count);
  END IF;
END;
