-- Lightweight FGA Alert Queue (simulates SIEM/webhook forwarding on unauthorized writes)
CREATE TABLE sec_admin.sec_fga_alert_queue (
  alert_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_schema   VARCHAR2(128) NOT NULL,
  object_name     VARCHAR2(128) NOT NULL,
  policy_name     VARCHAR2(128) NOT NULL,
  session_user    VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  client_ip       VARCHAR2(64)  DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
  alerted_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE ts_sec_data;

-- Canonical Oracle FGA event handler signature:
--   (object_schema VARCHAR2, object_name VARCHAR2, policy_name VARCHAR2)
-- Uses AUTHID DEFINER + AUTONOMOUS_TRANSACTION with mandatory ROLLBACK guard
-- (prevents ORA-06519; fail-closed so alert write failures are never silent).
CREATE OR REPLACE PROCEDURE sec_admin.prc_fga_alert_handler (
  object_schema IN VARCHAR2,
  object_name   IN VARCHAR2,
  policy_name   IN VARCHAR2
)
  AUTHID DEFINER
AS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO sec_admin.sec_fga_alert_queue (object_schema, object_name, policy_name)
  VALUES (
    prc_fga_alert_handler.object_schema,
    prc_fga_alert_handler.object_name,
    prc_fga_alert_handler.policy_name
  );
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END prc_fga_alert_handler;
/
SHOW ERRORS PROCEDURE sec_admin.prc_fga_alert_handler

-- ============================================================================
-- SECTION 3: Corrected Fine-Grained Auditing Policies (DBMS_FGA)
--   Fixes two common production FGA bugs:
--     1. Separates SELECT and UPDATE policies cleanly with exact statement_types.
--     2. Uses native SYS_CONTEXT('SYS_SESSION_ROLES', '<UPPERCASE_ROLE>') = 'FALSE'
--        instead of unsupported subqueries or lowercase role strings.
--   Note: In Oracle 23ai (pure Unified Auditing), DBMS_FGA records are written
--         directly to UNIFIED_AUDIT_TRAIL (AUDIT_TYPE = 'FineGrainedAudit');
--         DBMS_FGA.DB + DBMS_FGA.EXTENDED retains full 19c compatibility.
-- ============================================================================
BEGIN
  FOR pol IN (
    SELECT policy_name
      FROM sys.dba_audit_policies
     WHERE object_schema = 'SEC_ADMIN'
       AND object_name   = 'HR_EMPLOYEE_COMP'
  ) LOOP
    DBMS_FGA.DROP_POLICY(
      object_schema => 'SEC_ADMIN',
      object_name   => 'HR_EMPLOYEE_COMP',
      policy_name   => pol.policy_name
    );
  END LOOP;

  -- Policy 1: Audit SELECT of salary/allowance when user queries someone else's row
  --           AND does NOT hold ROLE_HR_PAYROLL_ADMIN (uppercase role name required)
  DBMS_FGA.ADD_POLICY(
    object_schema     => 'SEC_ADMIN',
    object_name       => 'HR_EMPLOYEE_COMP',
    policy_name       => 'FGA_HR_COMP_SENSITIVE_SELECT',
    audit_condition   => q'[SYS_CONTEXT('USERENV', 'SESSION_USER') <> UPPER(username) AND SYS_CONTEXT('SYS_SESSION_ROLES', 'ROLE_HR_PAYROLL_ADMIN') = 'FALSE']',
    audit_column      => 'BASE_SALARY, BONUS_ALLOWANCE',
    audit_column_opts => DBMS_FGA.ANY_COLUMNS,
    statement_types   => 'SELECT',
    enable            => TRUE,
    audit_trail       => DBMS_FGA.DB + DBMS_FGA.EXTENDED
  );

  -- Policy 2: Audit UPDATE of salary/allowance by any non-payroll-admin account
  --           and fire real-time alert handler
  DBMS_FGA.ADD_POLICY(
    object_schema     => 'SEC_ADMIN',
    object_name       => 'HR_EMPLOYEE_COMP',
    policy_name       => 'FGA_HR_COMP_SENSITIVE_UPDATE',
    audit_condition   => q'[SYS_CONTEXT('SYS_SESSION_ROLES', 'ROLE_HR_PAYROLL_ADMIN') = 'FALSE']',
    audit_column      => 'BASE_SALARY, BONUS_ALLOWANCE',
    audit_column_opts => DBMS_FGA.ANY_COLUMNS,
    handler_schema    => 'SEC_ADMIN',
    handler_module    => 'PRC_FGA_ALERT_HANDLER',
    statement_types   => 'UPDATE',
    enable            => TRUE,
    audit_trail       => DBMS_FGA.DB + DBMS_FGA.EXTENDED
  );
END;
/

-- ============================================================================
-- SECTION 4: Audit Trail Lifecycle & Retention Automation (DBMS_AUDIT_MGMT)
--   Prevents AUDSYS / SYSAUX tablespace exhaustion in production.
--   CRITICAL ORACLE PRODUCTION FIXES:
--     1. Uses AUTHID CURRENT_USER so the caller's AUDIT_ADMIN role remains active
--        (roles are disabled inside AUTHID DEFINER stored procedures!).
--     2. Uses SYS_EXTRACT_UTC(SYSTIMESTAMP) because Unified Audit timestamps
--        and SET_LAST_ARCHIVE_TIMESTAMP operate in UTC TIMESTAMP (not TZ).
--     3. Explicitly scopes Multitenant PDB calls with CONTAINER_CURRENT.
--     4. Schedules a rolling weekly watermark-advance job (JOB_ADVANCE_AUDIT_WATERMARK)
--        because DBMS_AUDIT_MGMT.CREATE_PURGE_JOB does NOT advance the static
--        LAST_ARCHIVE_TIMESTAMP on its own!
-- ============================================================================
CREATE OR REPLACE PROCEDURE sec_admin.prc_advance_audit_watermark (
  p_retention_days IN NUMBER DEFAULT 90
)
  AUTHID CURRENT_USER
AS
  v_cutoff_utc TIMESTAMP;
BEGIN
  IF p_retention_days IS NULL OR p_retention_days < 7 THEN
    RAISE_APPLICATION_ERROR(-20201, 'Minimum audit retention policy is 7 days.');
  END IF;

  v_cutoff_utc := SYS_EXTRACT_UTC(SYSTIMESTAMP) - NUMTODSINTERVAL(p_retention_days, 'DAY');

  DBMS_AUDIT_MGMT.SET_LAST_ARCHIVE_TIMESTAMP(
    audit_trail_type  => DBMS_AUDIT_MGMT.AUDIT_TRAIL_UNIFIED,
    last_archive_time => v_cutoff_utc,
    container         => DBMS_AUDIT_MGMT.CONTAINER_CURRENT
  );

  -- Optional mixed-mode 19c legacy FGA trail support (skipped safely in 23ai pure Unified mode)
  IF DBMS_AUDIT_MGMT.IS_CLEANUP_INITIALIZED(DBMS_AUDIT_MGMT.AUDIT_TRAIL_FGA_STD) THEN
    DBMS_AUDIT_MGMT.SET_LAST_ARCHIVE_TIMESTAMP(
      audit_trail_type  => DBMS_AUDIT_MGMT.AUDIT_TRAIL_FGA_STD,
      last_archive_time => v_cutoff_utc
    );
  END IF;

  DBMS_OUTPUT.PUT_LINE(
    'Unified Audit UTC archive watermark set to: ' ||
    TO_CHAR(v_cutoff_utc, 'YYYY-MM-DD HH24:MI:SS') || ' UTC'
  );
END prc_advance_audit_watermark;
/
SHOW ERRORS PROCEDURE sec_admin.prc_advance_audit_watermark

CREATE OR REPLACE PROCEDURE sec_admin.prc_purge_audit_trails (
  p_retention_days IN NUMBER DEFAULT 90
)
  AUTHID CURRENT_USER
AS
BEGIN
  -- 1. Advance UTC archive watermark to NOW - p_retention_days
  sec_admin.prc_advance_audit_watermark(p_retention_days => p_retention_days);

  -- 2. Purge Unified Audit Trail up to watermark in current PDB (FREEPDB1)
  DBMS_AUDIT_MGMT.CLEAN_AUDIT_TRAIL(
    audit_trail_type        => DBMS_AUDIT_MGMT.AUDIT_TRAIL_UNIFIED,
    use_last_arch_timestamp => TRUE,
    container               => DBMS_AUDIT_MGMT.CONTAINER_CURRENT
  );

  -- 3. Purge legacy FGA trail only if operating in 19c mixed-mode auditing
  IF DBMS_AUDIT_MGMT.IS_CLEANUP_INITIALIZED(DBMS_AUDIT_MGMT.AUDIT_TRAIL_FGA_STD) THEN
    DBMS_AUDIT_MGMT.CLEAN_AUDIT_TRAIL(
      audit_trail_type        => DBMS_AUDIT_MGMT.AUDIT_TRAIL_FGA_STD,
      use_last_arch_timestamp => TRUE
    );
  END IF;

  DBMS_OUTPUT.PUT_LINE('Audit trail purge completed for current PDB (retention=' || p_retention_days || 'd).');
END prc_purge_audit_trails;
/
SHOW ERRORS PROCEDURE sec_admin.prc_purge_audit_trails

-- Schedule:
--   1. Weekly watermark advancement job (runs Sunday 01:00 UTC)
--   2. Weekly DBMS_AUDIT_MGMT purge job (every 168 hours, container = CONTAINER_CURRENT)
BEGIN
  BEGIN
    DBMS_SCHEDULER.DROP_JOB(
      job_name => 'SEC_ADMIN.JOB_ADVANCE_AUDIT_WATERMARK',
      force    => TRUE
    );
  EXCEPTION
    WHEN OTHERS THEN NULL;
  END;

  DBMS_SCHEDULER.CREATE_JOB(
    job_name        => 'SEC_ADMIN.JOB_ADVANCE_AUDIT_WATERMARK',
    job_type        => 'PLSQL_BLOCK',
    job_action      => 'BEGIN sec_admin.prc_advance_audit_watermark(p_retention_days => 90); END;',
    start_date      => SYSTIMESTAMP,
    repeat_interval => 'FREQ=WEEKLY;BYDAY=SUN;BYHOUR=01;BYMINUTE=00;BYSECOND=00',
    enabled         => TRUE,
    comments        => 'Advances Unified Audit UTC archive watermark weekly before DBMS_AUDIT_MGMT purge.'
  );

  BEGIN
    DBMS_AUDIT_MGMT.DROP_PURGE_JOB(audit_trail_purge_name => 'JOB_PURGE_UNIFIED_AUDIT_90D');
  EXCEPTION
    WHEN OTHERS THEN NULL;
  END;

  -- Initialize watermark immediately so the purge job has a valid UTC baseline
  sec_admin.prc_advance_audit_watermark(p_retention_days => 90);

  DBMS_AUDIT_MGMT.CREATE_PURGE_JOB(
    audit_trail_type           => DBMS_AUDIT_MGMT.AUDIT_TRAIL_UNIFIED,
    audit_trail_purge_interval => 168, -- Weekly
    audit_trail_purge_name     => 'JOB_PURGE_UNIFIED_AUDIT_90D',
    use_last_arch_timestamp    => TRUE,
    container                  => DBMS_AUDIT_MGMT.CONTAINER_CURRENT
  );
END;
/

