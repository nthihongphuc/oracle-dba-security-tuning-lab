-- ============================================================================
-- SECTION 1: Unified Auditing Policy (Privileged DDL + Failed Authentication)
-- ============================================================================
BEGIN
  BEGIN
    EXECUTE IMMEDIATE 'NOAUDIT POLICY pol_dba_priv_and_auth';
  EXCEPTION
    WHEN OTHERS THEN NULL;
  END;

  BEGIN
    EXECUTE IMMEDIATE 'DROP AUDIT POLICY pol_dba_priv_and_auth';
  EXCEPTION
    WHEN OTHERS THEN NULL;
  END;
END;
/

CREATE AUDIT POLICY pol_dba_priv_and_auth
  ACTIONS
    CREATE USER,
    ALTER USER,
    DROP USER,
    GRANT,
    REVOKE,
    CREATE ROLE,
    DROP ROLE,
    ALTER SYSTEM
  WHEN 'SYS_CONTEXT(''USERENV'', ''SESSION_USER'') <> ''SYS'''
  EVALUATE PER SESSION;

AUDIT POLICY pol_dba_priv_and_auth;

