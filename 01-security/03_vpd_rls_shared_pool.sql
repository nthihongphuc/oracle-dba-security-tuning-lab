-- 2. Application Context & Trusted Setter Package
--    CRITICAL ORACLE INTERNALS FIX:
--      Inside an AUTHID DEFINER package or an AFTER LOGON database trigger,
--      session roles are DISABLED, so SYS_CONTEXT('SYS_SESSION_ROLES', ...)
--      always returns 'FALSE'! Instead, we inspect SYS.DBA_ROLE_PRIVS
--      hierarchically (direct SELECT granted to SEC_ADMIN in script 01) for
--      SYS_CONTEXT('USERENV', 'SESSION_USER') so both automatic logon triggers
--      and explicit session calls resolve ROLE_SEC_AUDITOR accurately.
CREATE OR REPLACE PACKAGE sec_admin.pkg_sec_context
  AUTHID DEFINER
AS
  PROCEDURE init_session_context;
END pkg_sec_context;
/
SHOW ERRORS PACKAGE sec_admin.pkg_sec_context

CREATE OR REPLACE PACKAGE BODY sec_admin.pkg_sec_context
AS
  PROCEDURE init_session_context IS
    v_session_user     VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
    v_has_auditor_role PLS_INTEGER   := 0;
    v_is_reviewer      VARCHAR2(1)   := 'N';
  BEGIN
    IF v_session_user = 'SEC_ADMIN' THEN
      v_is_reviewer := 'Y';
    ELSE
      SELECT COUNT(*)
        INTO v_has_auditor_role
        FROM sys.dba_role_privs
       WHERE granted_role = 'ROLE_SEC_AUDITOR'
       START WITH grantee = v_session_user
      CONNECT BY NOCYCLE PRIOR granted_role = grantee;

      IF v_has_auditor_role > 0 THEN
        v_is_reviewer := 'Y';
      END IF;
    END IF;

    DBMS_SESSION.SET_CONTEXT(
      namespace => 'CTX_HOTEL_SEC',
      attribute => 'IS_PRIVILEGED_REVIEWER',
      value     => v_is_reviewer
    );
  END init_session_context;
END pkg_sec_context;
/
SHOW ERRORS PACKAGE BODY sec_admin.pkg_sec_context

CREATE OR REPLACE CONTEXT ctx_hotel_sec USING sec_admin.pkg_sec_context;
GRANT EXECUTE ON sec_admin.pkg_sec_context TO role_hotel_clerk, role_sec_auditor;

-- PDB-scoped AFTER LOGON trigger automatically initializes CTX_HOTEL_SEC on connect.
-- Fails closed on unexpected error (leaving IS_PRIVILEGED_REVIEWER unset) while
-- never locking out DBA / application logins during package maintenance.
CREATE OR REPLACE TRIGGER sys.trg_freepdb1_init_sec_ctx
  AFTER LOGON ON DATABASE
BEGIN
  sec_admin.pkg_sec_context.init_session_context;
EXCEPTION
  WHEN OTHERS THEN
    NULL; -- Fail-closed: unset context denies privileged bypass without blocking login
END trg_freepdb1_init_sec_ctx;
/
SHOW ERRORS TRIGGER sys.trg_freepdb1_init_sec_ctx

-- 3. Shared-Pool-Friendly VPD Policy Function
--    STAFF DBA DESIGN NOTES (DBMS_RLS.STATIC vs CONTEXT_SENSITIVE vs DYNAMIC):
--      * ANTI-PATTERN 1 (Hard-parse storm):
--          RETURN 'owner_username = ''' || USER || '''';
--          Emits a user-specific string literal -> N cursors / ROW_LEVEL_SEC_MISMATCH!
--      * ANTI-PATTERN 2 (Classic DBMS_RLS.STATIC data-leak bug):
--          Putting PL/SQL IF SYS_CONTEXT(...) branching inside a DBMS_RLS.STATIC
--          policy function caches the FIRST caller's returned branch globally in
--          SGA for ALL subsequent users! Use DBMS_RLS.CONTEXT_SENSITIVE if the
--          predicate text itself must change per context value.
--      * GOLD STANDARD (Implemented below):
--          Zero PL/SQL user/role branching. Returns ONE invariant SQL predicate
--          referencing SYS_CONTEXT(...) evaluated by the SQL engine per execution.
--          Safe for DBMS_RLS.STATIC: policy function runs ONCE in SGA, zero
--          per-query PL/SQL overhead, and 1 shared cursor across all users.
CREATE OR REPLACE FUNCTION sec_admin.fn_vpd_owner_scope (
  p_schema IN VARCHAR2,
  p_object IN VARCHAR2
) RETURN VARCHAR2
AS
BEGIN
  RETURN q'[owner_username = SYS_CONTEXT('USERENV', 'SESSION_USER') OR SYS_CONTEXT('CTX_HOTEL_SEC', 'IS_PRIVILEGED_REVIEWER') = 'Y']';
END fn_vpd_owner_scope;
/
SHOW ERRORS FUNCTION sec_admin.fn_vpd_owner_scope

-- 4. Attach VPD Policy with DBMS_RLS.STATIC (Predicate text is 100% invariant)
BEGIN
  BEGIN
    DBMS_RLS.DROP_POLICY(
      object_schema => 'SEC_ADMIN',
      object_name   => 'GUEST_CONCIERGE_NOTES',
      policy_name   => 'POL_VPD_OWNER_SCOPE'
    );
  EXCEPTION
    WHEN OTHERS THEN NULL;
  END;

  DBMS_RLS.ADD_POLICY(
    object_schema   => 'SEC_ADMIN',
    object_name     => 'GUEST_CONCIERGE_NOTES',
    policy_name     => 'POL_VPD_OWNER_SCOPE',
    function_schema => 'SEC_ADMIN',
    policy_function => 'FN_VPD_OWNER_SCOPE',
    statement_types => 'SELECT, INSERT, UPDATE, DELETE',
    update_check    => TRUE,
    enable          => TRUE,
    policy_type     => DBMS_RLS.STATIC
  );
END;
/

-- 5. Verification Queries
--    Run this exact query from separate sessions (CLERK_ALICE, CLERK_BOB, SEC_AUDITOR):
--      SELECT /* VPD_CURSOR_SHARE_TEST */ note_id, owner_username, booking_ref
--        FROM sec_admin.guest_concierge_notes
--       ORDER BY note_id;
--
--    Expected row isolation (automatic via trg_freepdb1_init_sec_ctx on logon):
--      * CLERK_ALICE sees ONLY 2 rows (BK-2026-0001, BK-2026-0002).
--      * CLERK_BOB   sees ONLY 2 rows (BK-2026-0003, BK-2026-0004).
--      * CLERK_ALICE attempting INSERT with owner_username='CLERK_BOB' gets
--        ORA-28115: policy with check option violation (enforced by update_check=>TRUE).
--      * SEC_AUDITOR automatically sees all 4 rows (IS_PRIVILEGED_REVIEWER='Y').
--
--    Then run the Shared Pool cursor verification queries below as SYSDBA or SEC_ADMIN:

PROMPT === Active VPD Policies ===
SELECT object_owner, object_name, policy_name, pf_owner, package, function, policy_type, enable
  FROM sys.dba_policies
 WHERE object_owner = 'SEC_ADMIN'
   AND object_name  = 'GUEST_CONCIERGE_NOTES';

PROMPT === V$SQL Cursor Sharing Proof (Expect 1 SQL_ID & 1 Child Cursor Across N Users) ===
SELECT sql_id,
       child_number,
       executions,
       parse_calls,
       users_executing,
       SUBSTR(sql_text, 1, 120) AS sql_text_preview
  FROM v$sql
 WHERE sql_text LIKE '%VPD_CURSOR_SHARE_TEST%'
   AND UPPER(sql_text) NOT LIKE '%V$SQL%'
 ORDER BY sql_id, child_number;

PROMPT === Aggregated Cursor Count Check (distinct_sql_ids = 1, child_cursors = 1) ===
SELECT COUNT(DISTINCT sql_id) AS distinct_sql_ids,
       COUNT(*)               AS child_cursors,
       NVL(SUM(executions), 0) AS total_executions
  FROM v$sql
 WHERE sql_text LIKE '%VPD_CURSOR_SHARE_TEST%'
   AND UPPER(sql_text) NOT LIKE '%V$SQL%';

PROMPT === Cached VPD Predicate & Shared Cursor Mismatch Check (Expect ROW_LEVEL_SEC_MISMATCH = N) ===
SELECT p.sql_id,
       p.child_number,
       p.policy,
       p.predicate,
       sc.row_level_sec_mismatch
  FROM v$vpd_policy p
  LEFT JOIN v$sql_shared_cursor sc
    ON sc.sql_id       = p.sql_id
   AND sc.child_number = p.child_number
 WHERE p.object_owner = 'SEC_ADMIN'
   AND p.object_name  = 'GUEST_CONCIERGE_NOTES'
 ORDER BY p.sql_id, p.child_number;
