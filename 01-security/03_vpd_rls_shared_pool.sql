-- ============================================================================
-- File:        01-security/03_vpd_rls_shared_pool.sql
-- Purpose:     Shared-Pool-Friendly Virtual Private Database (VPD / RLS)
--              Demonstrates embedding SYS_CONTEXT('USERENV', 'SESSION_USER')
--              and an Application Context inside a pure invariant STATIC SQL
--              predicate (zero PL/SQL user-branching) so Oracle shares ONE
--              SQL_ID and ONE child cursor across all users (eliminating
--              V$SQL hard-parse storms and ROW_LEVEL_SEC_MISMATCH bloat).
-- Execution:   Run in FREEPDB1 connected as SYSDBA.
-- ============================================================================

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = sec_admin;

-- 1. Sample Sensitive Table Protected by Row-Level Security
CREATE TABLE sec_admin.guest_concierge_notes (
  note_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_username    VARCHAR2(128) NOT NULL,
  booking_ref       VARCHAR2(32)  NOT NULL,
  note_text         VARCHAR2(400) NOT NULL,
  confidential_flag CHAR(1) DEFAULT 'Y' NOT NULL CHECK (confidential_flag IN ('Y', 'N')),
  created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
) TABLESPACE ts_sec_data;

CREATE INDEX sec_admin.idx_gcn_owner_user
  ON sec_admin.guest_concierge_notes (owner_username)
  TABLESPACE ts_sec_data;

